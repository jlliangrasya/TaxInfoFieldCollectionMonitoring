// PDF, Excel and print helpers for reports. Every file carries the demo notice,
// the filters used, who generated it and when.
import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'
import writeXlsxFile from 'write-excel-file/browser'
import { format } from 'date-fns'
import { formatDate, formatDateTime } from '@/lib/format'
import { DEMO_NOTICE, LGU_NAME, OFFICE_NAME } from '@/lib/constants'

/**
 * Prevents "formula injection": a text cell beginning with = + - @ could be run
 * as a formula when the file is opened in a spreadsheet program.
 */
export function safeCell(value) {
  if (typeof value !== 'string') return value
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value
}

function moneyText(n) {
  if (n === null || n === undefined || n === '') return ''
  return `PHP ${Number(n).toLocaleString('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

function cellText(value, type) {
  if (value === null || value === undefined || value === '') return ''
  if (type === 'money') return moneyText(value)
  if (type === 'number') return Number(value).toLocaleString('en-PH')
  if (type === 'date') return formatDate(value)
  return String(value)
}

function fileName(report, ext) {
  return `${report.id.replace(/_/g, '-')}-${format(new Date(), 'yyyyMMdd-HHmm')}.${ext}`
}

export function exportPdf(report) {
  const landscape = report.columns.length > 6
  const doc = new jsPDF({ orientation: landscape ? 'landscape' : 'portrait', unit: 'pt', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(9)
  doc.setTextColor(180, 83, 9)
  doc.text(DEMO_NOTICE, pageWidth / 2, 28, { align: 'center' })
  doc.setTextColor(20, 30, 60)
  doc.setFontSize(11)
  doc.text(`${OFFICE_NAME} — ${LGU_NAME}`, 40, 52)
  doc.setFontSize(15)
  doc.text(report.title, 40, 72)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(80, 90, 110)
  doc.text(doc.splitTextToSize(report.filtersText, pageWidth - 80), 40, 88)
  doc.text(`Generated by ${report.generatedBy} on ${formatDateTime(report.generatedAt)}`, 40, 102)

  const body = report.rows.map((r) => report.columns.map((c) => cellText(r[c.key], c.type)))
  const foot = report.totals ? [report.columns.map((c) => cellText(report.totals[c.key], c.type))] : undefined

  autoTable(doc, {
    startY: 114,
    head: [report.columns.map((c) => c.label)],
    body: body.length ? body : [[{ content: 'No records match the selected filters.', colSpan: report.columns.length }]],
    foot,
    showFoot: 'lastPage',
    styles: { fontSize: 8, cellPadding: 4, overflow: 'linebreak' },
    headStyles: { fillColor: [30, 58, 120], textColor: 255 },
    footStyles: { fillColor: [232, 236, 245], textColor: [20, 30, 60], fontStyle: 'bold' },
    columnStyles: Object.fromEntries(
      report.columns.map((c, i) => [i, c.type === 'money' || c.type === 'number' ? { halign: 'right' } : {}]),
    ),
    didDrawPage: () => {
      const h = doc.internal.pageSize.getHeight()
      doc.setFontSize(8)
      doc.setTextColor(120)
      doc.text(`${DEMO_NOTICE} · Page ${doc.getCurrentPageInfo().pageNumber}`, pageWidth / 2, h - 18, { align: 'center' })
    },
  })
  doc.save(fileName(report, 'pdf'))
}

export async function exportExcel(report) {
  const bold = { fontWeight: 'bold' }
  const toCell = (value, type, extra = {}) => {
    if (value === null || value === undefined || value === '') return null
    if (type === 'money') return { value: Number(value), type: Number, format: '#,##0.00', ...extra }
    if (type === 'number') return { value: Number(value), type: Number, ...extra }
    if (type === 'date') return { value: formatDate(value), type: String, ...extra }
    return { value: safeCell(String(value)), type: String, ...extra }
  }
  const data = [
    [{ value: DEMO_NOTICE, type: String, ...bold }],
    [{ value: `${OFFICE_NAME} — ${LGU_NAME}`, type: String }],
    [{ value: report.title, type: String, fontWeight: 'bold', fontSize: 14 }],
    [{ value: safeCell(report.filtersText), type: String }],
    [{ value: `Generated by ${report.generatedBy} on ${formatDateTime(report.generatedAt)}`, type: String }],
    [],
    report.columns.map((c) => ({ value: c.label, type: String, ...bold, backgroundColor: '#E8ECF5' })),
    ...report.rows.map((r) => report.columns.map((c) => toCell(r[c.key], c.type))),
  ]
  if (report.totals) data.push(report.columns.map((c) => toCell(report.totals[c.key], c.type, bold)))

  await writeXlsxFile(data, {
    sheet: 'Report',
    columns: report.columns.map((c) => ({ width: c.key === 'remarks' ? 40 : c.type === 'money' ? 18 : 22 })),
  }).toFile(fileName(report, 'xlsx'))
}
